// Builds db/boards.json from PlatformIO's open board manifests (Apache-2.0, https://github.com/platformio).
// Usage: node scripts/import-boards.mjs
// Downloads each platform repo as a .tar.gz from codeload.github.com (no API, no rate limit) and reads boards/*.json.
import fs from 'node:fs';
import zlib from 'node:zlib';

const PLATFORMS = [
  'atmelavr', 'atmelmegaavr', 'atmelsam', 'espressif32', 'espressif8266', 'raspberrypi', 'ststm32', 'ststm8', 'teensy',
  'timsp430', 'titiva', 'nordicnrf51', 'nordicnrf52', 'nxplpc', 'nxpimxrt', 'freescalekinetis', 'siliconlabsefm32',
  'microchippic32', 'sifive', 'riscv', 'riscv_gap', 'shakti', 'chipsalliance', 'openhw', 'maxim32', 'wiznet7500',
  'intel_mcs51', 'intel_arc32', 'lattice_ice40', 'renesas-ra', 'samsung_artik',
];
const ARCH = {
  atmelavr: 'AVR', atmelmegaavr: 'AVR', ststm8: 'STM8', timsp430: 'MSP430', intel_mcs51: '8051', espressif8266: 'Xtensa',
  microchippic32: 'MIPS', sifive: 'RISC-V', riscv: 'RISC-V', riscv_gap: 'RISC-V', shakti: 'RISC-V', chipsalliance: 'RISC-V',
  openhw: 'RISC-V', lattice_ice40: 'FPGA', intel_arc32: 'ARC',
};
// the repo's boards/*.json files, straight out of its tarball: {name: parsedJson}
async function boardFiles(repo) {
  let buf = null;
  for (let i = 0; i < 4 && !buf; i++) {
    const r = await fetch(`https://codeload.github.com/${repo}/tar.gz/HEAD`, {headers: {'User-Agent': 'parts-bin-board-import'}});
    if (r.status === 404) return {};
    if (r.ok) buf = zlib.gunzipSync(Buffer.from(await r.arrayBuffer()));
    else await new Promise((res) => setTimeout(res, 1000 * 2 ** i));
  }
  if (!buf) throw new Error(`failed: ${repo}`);
  const out = {};
  let longName = null;
  for (let off = 0; off + 512 <= buf.length; ) {
    const h = buf.subarray(off, off + 512);
    if (h.every((x) => x === 0)) break;
    const str = (a, b) => h.subarray(a, b).toString('utf8').replace(/\0.*$/s, '');
    const size = parseInt(str(124, 136).trim() || '0', 8);
    const type = String.fromCharCode(h[156]);
    let name = longName || (str(345, 500) ? `${str(345, 500)}/${str(0, 100)}` : str(0, 100));
    longName = null;
    const body = buf.subarray(off + 512, off + 512 + size);
    if (type === 'L') longName = body.toString('utf8').replace(/\0.*$/s, '');
    else if (type === 'x') { const m = /\d+ path=(.*)\n/.exec(body.toString('utf8')); if (m) longName = m[1]; }
    else if ((type === '0' || type === '\0') && /^[^/]+\/boards\/[^/]+\.json$/.test(name)) {
      try { out[name.split('/').pop().replace(/\.json$/, '')] = JSON.parse(body.toString('utf8')); } catch {}
    }
    off += 512 + Math.ceil(size / 512) * 512;
  }
  return out;
}
// arch for platforms that mix cores (ESP32 has Xtensa and RISC-V parts, STM32 spans Cortex-M0..M7)
function archOf(platform, b) {
  if (ARCH[platform]) return ARCH[platform];
  const core = String(b.build?.core || ''), cpu = String(b.build?.cpu || ''), mcu = String(b.build?.mcu || '').toLowerCase();
  if (platform === 'espressif32') return /esp32c|esp32h|esp32p/.test(mcu) ? 'RISC-V' : 'Xtensa';
  if (/cortex-m(\d+\+?)/i.test(cpu)) return `ARM Cortex-${cpu.match(/cortex-(m\d+\+?)/i)[1].toUpperCase()}`;
  if (/riscv/i.test(cpu + core)) return 'RISC-V';
  return 'ARM';
}
const slug = (s) => String(s).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

const boards = [];
for (const plat of PLATFORMS) {
  const got = Object.entries(await boardFiles(`platformio/platform-${plat}`));
  for (const [id, b] of got) {
    const fcpu = parseInt(String(b.build?.f_cpu || '').replace(/L$/, ''), 10);
    boards.push({
      key: `${plat}:${id}`, name: b.name, vendor: b.vendor || '', mcu: String(b.build?.mcu || '').toUpperCase(), arch: archOf(plat, b),
      mhz: fcpu ? Math.round(fcpu / 1e6) : null,
      flashKB: b.upload?.maximum_size ? Math.round(b.upload.maximum_size / 1024) : null,
      ramKB: b.upload?.maximum_ram_size ? Math.round(b.upload.maximum_ram_size / 1024) : null,
      wireless: (b.connectivity || []).filter((c) => /wifi|bluetooth|lora|zigbee|thread|ethernet|cellular|can/i.test(c)),
      frameworks: b.frameworks || [], url: b.url || '', platform: plat, pio: id,
    });
  }
  console.log(`${plat}: ${got.length}`);
}
// one entry per distinct name (several platforms ship the same board)
const seen = new Map();
for (const b of boards.sort((a, z) => a.name.localeCompare(z.name))) if (b.name && !seen.has(slug(b.name))) seen.set(slug(b.name), b);
const out = [...seen.values()];
fs.writeFileSync(new URL('../db/boards.json', import.meta.url), JSON.stringify({
  $comment: 'Microcontroller and development boards. Generated by scripts/import-boards.mjs from PlatformIO board manifests (https://github.com/platformio, Apache License 2.0; see NOTICE). Do not edit by hand: add missing boards to db/boards-extra.json instead.',
  generated: new Date().toISOString().slice(0, 10), boards: out,
}));
console.log(`${out.length} boards written`);
